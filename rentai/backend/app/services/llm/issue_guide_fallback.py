def get_fallback_guide(title: str, description: str) -> Optional[Dict[str, Any]]:
    """
    이슈 제목과 설명에서 키워드를 찾아 fallback 가이드를 반환합니다.
    
    Args:
        title: 이슈 제목
        description: 이슈 설명
    
    Returns:
        가이드 딕셔너리 또는 None
    """
    if not title:
        return None
    
    # 제목과 설명을 합쳐서 검색
    search_text = (title + " " + description).lower()
    
    # 키워드 매칭 (긴 키워드부터 우선 매칭)
    for key, guide in ISSUE_GUIDES_FALLBACK.items():
        if key.lower() in search_text:
            return guide
    
    return None
